-- ---------------------------------------------------------------------
--  Community rating per game, calculated from visible reviews only
-- ---------------------------------------------------------------------
CREATE VIEW v_game_ratings AS
  SELECT game_id,
         AVG(rating) AS avg_rating,
         COUNT(*)    AS review_count
  FROM reviews
  WHERE is_hidden = 0
  GROUP BY game_id;

