  CONSTRAINT fk_reports_user   FOREIGN KEY (reporter_id) REFERENCES users(id)   ON DELETE CASCADE
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
--  Personal data: wishlist and preferences
