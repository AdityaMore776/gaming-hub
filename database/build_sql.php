  CONSTRAINT fk_gg_game  FOREIGN KEY (game_id)  REFERENCES games(id)  ON DELETE CASCADE,
  CONSTRAINT fk_gg_genre FOREIGN KEY (genre_id) REFERENCES genres(id) ON DELETE CASCADE
) ENGINE=InnoDB;

