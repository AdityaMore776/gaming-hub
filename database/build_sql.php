foreach ($data['users'] as [$username, $email, $role, $password, $bio]) {
    $userIds[$username] = $i;
    $hash = password_hash($password, PASSWORD_DEFAULT);
    $rows[] = sprintf("(%d, %s, %s, %s, %s, %s, DATE_SUB(NOW(), INTERVAL %d DAY))",
        $i, q($username), q($email), q($hash), q($role), q($bio === '' ? null : $bio), 200 - $i * 7);
    $i++;
}
$out[] = "-- Demo accounts (development passwords are listed in README.md)\n";
$out[] = "INSERT INTO users (id, username, email, password_hash, role, bio, created_at) VALUES\n  " . implode(",\n  ", $rows) . ";\n";

// ---------------------------------------------------------------- games
$gameIds = [];
$gameRows = $attrRows = $ggRows = $gpRows = [];
$i = 1;
foreach ($data['games'] as $g) {
    [$title, $year, $dev, $genres, $platforms, $modes, $dna, $session, $hours, $desc, $pros, $cons, $featured] = $g;
    $gameIds[$title] = $i;
    $gameRows[] = sprintf("(%d, %s, %s, %s, %d, %s, %s, %s, %d, %d, %d, %d)",
        $i, q($title), q(slugify($title)), q($dev), $year, q($desc),
        q(str_replace('|', "\n", $pros)), q(str_replace('|', "\n", $cons)),
        str_contains($modes, 'S') ? 1 : 0, str_contains($modes, 'C') ? 1 : 0,
        str_contains($modes, 'M') ? 1 : 0, $featured ? 1 : 0);
    $attrRows[] = sprintf("(%d, %d, %d, %d, %d, %d, %s, %s)",
        $i, $dna[0], $dna[1], $dna[2], $dna[3], $dna[4], q($session), $hours === null ? 'NULL' : (int) $hours);
    foreach ($genres as $pos => $slug) {
        if (!isset($genreIds[$slug])) {
            fwrite(STDERR, "Unknown genre '$slug' for $title\n");
            exit(1);
        }
        $ggRows[] = "($i, {$genreIds[$slug]}, $pos)";
    }
    foreach ($platforms as $slug) {
        if (!isset($platformIds[$slug])) {
            fwrite(STDERR, "Unknown platform '$slug' for $title\n");
            exit(1);
        }
        $gpRows[] = "($i, {$platformIds[$slug]})";
    }
    $i++;
}
$out[] = "INSERT INTO games (id, title, slug, developer, release_year, description, pros, cons, has_single_player, has_coop, has_multiplayer, is_featured) VALUES\n  "
    . implode(",\n  ", $gameRows) . ";\n";
$out[] = "-- Game DNA (story, combat, exploration, difficulty, replayability) — editorial estimates\n";
$out[] = "INSERT INTO game_attributes (game_id, story_score, combat_score, exploration_score, difficulty_score, replayability_score, session_length, completion_hours) VALUES\n  "
    . implode(",\n  ", $attrRows) . ";\n";
$out[] = "INSERT INTO game_genres (game_id, genre_id, position) VALUES\n  " . implode(",\n  ", $ggRows) . ";\n";
$out[] = "INSERT INTO game_platforms (game_id, platform_id) VALUES\n  " . implode(",\n  ", $gpRows) . ";\n";

// ---------------------------------------------------------------- reviews
$reviewIds = []; // "title|username" => id
$rows = [];
$i = 1;
foreach ($data['reviews'] as $title => $list) {
    if (!isset($gameIds[$title])) {
        fwrite(STDERR, "Review for unknown game '$title'\n");
        exit(1);
    }
    foreach ($list as [$username, $rating, $body, $daysAgo]) {
        $reviewIds["$title|$username"] = $i;
        $rows[] = sprintf("(%d, %d, %d, %d, %s, DATE_SUB(NOW(), INTERVAL %d DAY))",
            $i, $gameIds[$title], $userIds[$username], $rating, q($body), $daysAgo);
        $i++;
    }
}
$out[] = "-- Demo reviews written by the project team for demonstration purposes\n";
$out[] = "INSERT INTO reviews (id, game_id, user_id, rating, body, created_at) VALUES\n  " . implode(",\n  ", $rows) . ";\n";

// Helpful votes: each review gets 0-6 votes from other (non-spam) users.
$voters = array_values(array_diff(array_keys($userIds), ['admin', 'free_codes_4u']));
$rows = [];
foreach ($data['reviews'] as $title => $list) {
    foreach ($list as [$username, $rating]) {
        if ($username === 'free_codes_4u') {
            continue;
        }
        $count = mt_rand(0, $rating >= 4 ? 6 : 3);
        $pool = array_values(array_diff($voters, [$username]));
        shuffle($pool);
        foreach (array_slice($pool, 0, $count) as $voter) {
            $rows[] = sprintf('(%d, %d)', $reviewIds["$title|$username"], $userIds[$voter]);
        }
    }
}
$out[] = "INSERT INTO review_votes (review_id, user_id) VALUES\n  " . implode(",\n  ", $rows) . ";\n";

$rows = [];
foreach ($data['reports'] as [$reporter, $title, $author, $reason, $details]) {
    $rows[] = sprintf("(%d, %d, %s, %s)", $reviewIds["$title|$author"], $userIds[$reporter], q($reason), q($details === '' ? null : $details));
}
$out[] = "INSERT INTO review_reports (review_id, reporter_id, reason, details) VALUES\n  " . implode(",\n  ", $rows) . ";\n";

// ---------------------------------------------------------------- personal data
$rows = [];
foreach ($data['wishlist'] as $username => $titles) {
    foreach ($titles as $title) {
        $rows[] = sprintf('(%d, %d)', $userIds[$username], $gameIds[$title]);
    }
}
$out[] = "INSERT INTO wishlists (user_id, game_id) VALUES\n  " . implode(",\n  ", $rows) . ";\n";

$rows = [];
foreach ($data['preferences'] as $username => $p) {
    $rows[] = sprintf("(%d, %d, %d, %s, %s, %s, %s, %s)", $userIds[$username],
        $genreIds[$p['genre']], $platformIds[$p['platform']], q($p['mood']), q($p['play_style']),
        q($p['difficulty']), q($p['session']), q($p['focus']));
}
$out[] = "INSERT INTO user_preferences (user_id, genre_id, platform_id, mood, play_style, difficulty, session, focus) VALUES\n  "
    . implode(",\n  ", $rows) . ";\n";

$rows = [];
foreach ($data['user_genres'] as $username => $slugs) {
    foreach ($slugs as $slug) {
        $rows[] = sprintf('(%d, %d)', $userIds[$username], $genreIds[$slug]);
    }
}
$out[] = "INSERT INTO user_genres (user_id, genre_id) VALUES\n  " . implode(",\n  ", $rows) . ";\n";

$rows = [];
foreach ($data['user_platforms'] as $username => $slugs) {
    foreach ($slugs as $slug) {
        $rows[] = sprintf('(%d, %d)', $userIds[$username], $platformIds[$slug]);
    }
}
$out[] = "INSERT INTO user_platforms (user_id, platform_id) VALUES\n  " . implode(",\n  ", $rows) . ";\n";

file_put_contents(__DIR__ . '/gaming_hub.sql', implode("\n", $out));
printf("Wrote gaming_hub.sql: %d genres, %d platforms, %d games, %d users, %d reviews\n",
    count($genreIds), count($platformIds), count($gameIds), count($userIds), count($reviewIds));
